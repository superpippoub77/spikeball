// traduce un testo; depth limita la ricorsione sulle parti variabili
function T(s, depth = 0) {
  if (typeof s !== 'string' || !s || !I18N.lang || depth > 7) return s;
  const L = LANG_IX[I18N.lang];
  if (depth === 0 && I18N.cache.has(s)) return I18N.cache.get(s);
  let out = null;
  const row = I18N.exact.get(s);
  if (row) out = row[L];
  // spazi iniziali/finali: si traduce il testo interno
  if (out === null && !s.includes('\n')) { const m = s.match(/^(\s*)([\s\S]*?\S)(\s*)$/); if (m && (m[1] || m[3])) { const c = T(m[2], depth + 1); if (c !== m[2]) out = m[1] + c + m[3]; } }
  // modelli con parti variabili (i testi su più righe solo con modelli su più righe)
  const multi = s.includes('\n');
  if (out === null) for (const t of I18N.tpl) {
    if (multi && !t.multi) continue;
    const m = s.match(t.re);
    if (!m) continue;
    const vals = []; t.order.forEach((n, k) => { vals[n] = T(m[k + 1], depth + 1); });
    out = t.row[L].replace(/\{(\d)\}/g, (_, n) => vals[n] ?? ''); break;
  }
  // più righe: riga per riga
  if (out === null && multi) { const p = s.split('\n').map(x => T(x, depth + 1)); out = p.join('\n'); }
  // comandi separati da più spazi, " · " o " | ": pezzo per pezzo
  if (out === null && /\s{3,}|\s·\s|\s\|\s/.test(s)) {
    const parts = s.split(/(\s{3,}|\s+·\s+|\s+\|\s+)/), tr = parts.map((x, i) => i % 2 ? x : T(x, depth + 1));
    if (tr.some((x, i) => x !== parts[i])) out = tr.join('');
  }
  if (out === null) out = s;
  if (depth === 0) { if (I18N.cache.size > 4000) I18N.cache.clear(); I18N.cache.set(s, out); }
  return out;
}

